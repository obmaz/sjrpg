"""Measure generated silhouettes; pack immutable runtime images and root metadata."""
from pathlib import Path
import hashlib
import json
import numpy as np
from scipy import ndimage
from PIL import Image

ROOT=Path(__file__).resolve().parents[1]
DOC=ROOT/'docs/art/quarter-view-abbey'
ART=ROOT/'flutter_game/art'
source=DOC/'abbey-original.png'
rgba=np.asarray(Image.open(source).convert('RGBA')).copy()
r,g,b=[rgba[:,:,i].astype(float) for i in range(3)]
fringe=ndimage.binary_dilation(rgba[:,:,3]<=20,iterations=3)
rgba[(r>130)&(r>g*1.7)&(r>b*1.7)&fringe,3]=0
abbey=Image.new('RGBA',(rgba.shape[1]+8,rgba.shape[0]+8))
abbey.alpha_composite(Image.fromarray(rgba),(4,4))
abbey.save(ART/'forest-quest-chapel.webp',quality=96,method=6,exact=True)
plant_source=DOC/'undergrowth-original.png'
pixels=np.asarray(Image.open(plant_source).convert('RGBA')).copy()
labels,_=ndimage.label(pixels[:,:,3]>20)
areas=np.bincount(labels.ravel());ids=np.argsort(areas[1:])[-6:]+1
if min(areas[ids])<50000:raise ValueError('Six independent complete foliage silhouettes required')
centers=ndimage.center_of_mass(pixels[:,:,3]>20,labels,ids)
ordered=sorted(zip(ids,centers),key=lambda p:(p[1][0]>pixels.shape[0]/2,p[1][1]))
feet=[(287,421),(790,433),(1286,438),(245,959),(754,967),(1295,971)]
heights=[78,105,65,220,82,64]
names=['fern','bramble','wildflowers','birch','yew-ivy','moss-stones']
atlas=Image.new('RGBA',(960,640));frames=[]
for i,(ident,_) in enumerate(ordered):
 ys,xs=np.nonzero(labels==ident)
 box=(max(0,int(xs.min())-3),max(0,int(ys.min())-3),min(pixels.shape[1],int(xs.max())+4),min(pixels.shape[0],int(ys.max())+4))
 own=ndimage.binary_dilation(labels==ident,iterations=2)
 isolated=pixels.copy();isolated[~own,3]=0
 tile=Image.fromarray(isolated).crop(box)
 scale=min(296/tile.width,296/tile.height)
 size=(round(tile.width*scale),round(tile.height*scale))
 resized=tile.resize(size,Image.Resampling.LANCZOS)
 x=i%3*320+(320-size[0])//2;y=i//3*320+(320-size[1])//2
 atlas.alpha_composite(resized,(x,y))
 foot=(x+(feet[i][0]-box[0])*size[0]/tile.width,y+(feet[i][1]-box[1])*size[1]/tile.height)
 frames.append({'name':names[i],'sourceRect':box,'packedRect':[x,y,*size],'foot':[round(v,4) for v in foot],'height':heights[i]})
atlas.save(ART/'forest-undergrowth.webp',quality=95,method=6,exact=True)
lines=["// Generated by tools/prepare-abbey-environment.py from measured alpha bounds.","import 'dart:ui';",'', 'const undergrowthFrames = [']
for f in frames:
 x,y,w,h=f['packedRect'];fx,fy=f['foot']
 lines.append(f"  (source: Rect.fromLTWH({x}, {y}, {w}, {h}), foot: Offset({fx}, {fy}), height: {f['height']}.0),")
lines.append('];\n')
(ROOT/'flutter_game/lib/forest_undergrowth_frames.dart').write_text('\n'.join(lines))
record={'generator':'image_gen','processor':'tools/prepare-abbey-environment.py','abbey':{'source':str(source.relative_to(ROOT)),'sha256':hashlib.sha256(source.read_bytes()).hexdigest(),'runtime':'flutter_game/art/forest-quest-chapel.webp','size':abbey.size,'padding':4},'undergrowth':{'source':str(plant_source.relative_to(ROOT)),'sha256':hashlib.sha256(plant_source.read_bytes()).hexdigest(),'runtime':'flutter_game/art/forest-undergrowth.webp','size':atlas.size,'frames':frames}}
(DOC/'runtime-provenance.json').write_text(json.dumps(record,indent=4)+'\n')
print(json.dumps({'abbey':abbey.size,'foliage':frames}))
