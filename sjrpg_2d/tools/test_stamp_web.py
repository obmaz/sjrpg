#!/usr/bin/env python3
"""Standalone tests: python3 tools/test_stamp_web.py (no engine required)."""

import hashlib
import json
from pathlib import Path
import tempfile
import unittest

from stamp_web import read_config, stamp


class StampWebTest(unittest.TestCase):
    def setUp(self):
        self.temporary = tempfile.TemporaryDirectory()
        self.addCleanup(self.temporary.cleanup)
        self.directory = Path(self.temporary.name)

    def export(self, payload):
        (self.directory / "index.pck").write_bytes(payload)
        config = {"executable": "index", "args": [], "canvasResizePolicy": 2,
                  "fileSizes": {"index.pck": len(payload), "index.wasm": 12345}}
        html = "<script>\nconst GODOT_CONFIG = " + json.dumps(config, indent=2) + ";\nnew Engine(GODOT_CONFIG);\n</script>\n"
        (self.directory / "index.html").write_text(html)

    def config(self):
        return read_config((self.directory / "index.html").read_text())[0]

    def test_hash_payload_metadata_routes_and_rerun(self):
        payload = b"GDPC\x00native mesh and skeletal animation\xff"
        self.export(payload)
        result = stamp(self.directory)
        expected = hashlib.sha256(payload).hexdigest()
        self.assertEqual(result["sha256"], expected)
        self.assertEqual(result["main_pack"], "index-" + expected[:20] + ".pck")
        self.assertEqual((self.directory / result["main_pack"]).read_bytes(), payload)
        self.assertFalse((self.directory / "index.pck").exists())
        self.assertEqual(self.config()["mainPack"], result["main_pack"])
        self.assertEqual(self.config()["fileSizes"], {"index.wasm": 12345, result["main_pack"]: len(payload)})
        html = (self.directory / "index.html").read_bytes()
        self.assertEqual((self.directory / "3d.html").read_bytes(), html)
        self.assertIn(('window.__sjrpgBuild = "' + expected + '";').encode(), html)
        self.assertEqual(stamp(self.directory), result)
        self.assertEqual((self.directory / "index.html").read_bytes(), html)
        self.assertEqual(len(list(self.directory.glob("*.pck"))), 1)

    def test_next_export_only_cleans_owned_stale_packs(self):
        self.export(b"first build")
        previous = stamp(self.directory)["main_pack"]
        unrelated = self.directory / "dlc.pck"
        unrelated.write_bytes(b"leave untouched")
        near_match = self.directory / "index-custom.pck"
        near_match.write_bytes(b"not generated by this helper")
        self.export(b"second build")
        current = stamp(self.directory)["main_pack"]
        self.assertNotEqual(previous, current)
        self.assertFalse((self.directory / previous).exists())
        self.assertEqual(unrelated.read_bytes(), b"leave untouched")
        self.assertTrue(near_match.exists())
        self.assertEqual(set(self.config()["fileSizes"]), {"index.wasm", current})

    def test_invalid_config_does_not_rename_pack(self):
        self.export(b"pack must survive")
        (self.directory / "index.html").write_text("<html>missing config</html>")
        with self.assertRaisesRegex(ValueError, "GODOT_CONFIG"):
            stamp(self.directory)
        self.assertEqual((self.directory / "index.pck").read_bytes(), b"pack must survive")


if __name__ == "__main__":
    unittest.main()
